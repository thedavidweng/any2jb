var (
	NeutralKeyboardReport = [8]byte{}
	NeutralGamepadReport  = [8]byte{0, 0, 8, 128, 128, 128, 128, 0}
)

type FunctionSpec struct {
	Name          string
	Subclass      uint8
	Protocol      uint8
	ReportLength  uint8
	ReportDesc    []byte
	NeutralReport [8]byte
}

type Spec struct {
	Controller    string
	VendorID      string
	ProductID     string
	BCDDevice     string
	BCDUSB        string
	Manufacturer  string
	Product       string
	SerialNumber  string
	Configuration string
	Functions     []FunctionSpec
}

func KeyboardSpec(controller string) Spec {
	return Spec{
		Controller:    controller,
		VendorID:      "0x1d6b",
		ProductID:     "0x1234",
		BCDDevice:     "0x0100",
		BCDUSB:        "0x0200",
		Manufacturer:  "mac2jb",
		Product:       "USB HID Keyboard",
		SerialNumber:  "MAC2JBKEYBOARD",
		Configuration: "HID",
		Functions: []FunctionSpec{{
			Name:          "hid.usb0",
			Subclass:      1,
			Protocol:      1,
			ReportLength:  8,
			ReportDesc:    BootKeyboardReportDescriptor,
			NeutralReport: NeutralKeyboardReport,
		}},
	}
}

